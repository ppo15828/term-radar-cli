#!/usr/bin/env python3
import requests, re, sys
from datetime import date
from collections import Counter

# Simple demo: fetch top stories from Hacker News, extract AI-related terms
HN_TOP = "https://hacker-news.firebaseio.com/v0/topstories.json"
ITEM = "https://hacker-news.firebaseio.com/v0/item/{}.json"
KEYWORDS = ['AI','GPT','LLM','model','agent','deep learning','neural','transformer','openai','claude']

def get_json(url):
    try:
        r = requests.get(url, timeout=10)
        r.raise_for_status()
        return r.json()
    except:
        return None

def extract_terms(text):
    # Simple camelCase / term extraction: words with uppercase or after keyword
    words = re.findall(r'\b[A-Z][a-z]+(?:[A-Z][a-z]+)*\b', text)
    return [w for w in words if any(k.lower() in w.lower() for k in KEYWORDS)]

def scan_hn(limit=30):
    ids = get_json(HN_TOP)
    if not ids:
        return []
    terms = Counter()
    for i in ids[:limit]:
        item = get_json(ITEM.format(i))
        if item and item.get('type') == 'story':
            title = item.get('title','')
            url = item.get('url','')
            terms.update(extract_terms(f"{title} {url}"))
            # also check text if available
            if item.get('text'):
                terms.update(extract_terms(item['text']))
    return terms.most_common(10)

def main():
    today = date.today().isoformat()
    print(f"# New AI Term Radar - {today}\n")
    terms = scan_hn()
    if not terms:
        print("No new terms detected today. Try later.")
    else:
        print("| Rank | Term | Mentions |")
        print("|------|------|----------|")
        for i, (term, cnt) in enumerate(terms, 1):
            print(f"| {i} | {term} | {cnt} |")
    print("\n*Generated by term-radar-cli demo*")

if __name__ == "__main__":
    main()
